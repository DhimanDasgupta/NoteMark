# ------------------------------------------------------------------------------
# Gradle Execution Wrapper
# ------------------------------------------------------------------------------
run_gradle() {
    local task_desc="$1"
    shift
    local tasks=("$@")

    if [[ ${#tasks[@]} -eq 0 ]]; then
        return 0
    fi

    log_step "$task_desc"
    log_info "Executing Gradle tasks: ${BOLD}${tasks[*]}${RESET}"
    if [[ ${#GRADLE_ARGS[@]} -gt 0 ]]; then
        log_info "Extra Gradle flags: ${DIM}${GRADLE_ARGS[*]}${RESET}"
    fi

    if [[ $DRY_RUN -eq 1 ]]; then
        if [[ ${#GRADLE_ARGS[@]} -gt 0 ]]; then
            echo -e "${YELLOW}[DRY-RUN]${RESET} Would run: $GRADLEW ${tasks[*]} ${GRADLE_ARGS[*]}"
        else
            echo -e "${YELLOW}[DRY-RUN]${RESET} Would run: $GRADLEW ${tasks[*]}"
        fi
        return 0
    fi

    local task_start
    task_start=$(date +%s)

    # Run the gradle wrapper
    if [[ ${#GRADLE_ARGS[@]} -gt 0 ]]; then
        "$GRADLEW" "${tasks[@]}" "${GRADLE_ARGS[@]}"
    else
        "$GRADLEW" "${tasks[@]}"
    fi

    local task_end
    task_end=$(date +%s)
    local task_duration=$((task_end - task_start))
    log_success "$task_desc completed in $(format_time $task_duration)"
}

# ------------------------------------------------------------------------------
# Diagnostics Command
# ------------------------------------------------------------------------------
run_diagnostics() {
    print_banner
    log_step "Project & Environment Diagnostics"
    echo -e "${BOLD}Project Directory:${RESET}  $PROJECT_ROOT"
    echo -e "${BOLD}Operating System:${RESET}   $(uname -srm)"
    echo -e "${BOLD}Shell:${RESET}              $SHELL ($BASH_VERSION)"
    
    echo -e "\n${BOLD}Java Environment:${RESET}"
    if command -v java >/dev/null 2>&1; then
        java -version 2>&1 | sed 's/^/  /'
        echo "  JAVA_HOME: ${JAVA_HOME:-<not set>}"
    else
        echo "  Java not found!"
    fi

    echo -e "\n${BOLD}Android SDK Environment:${RESET}"
    echo "  ANDROID_HOME:     ${ANDROID_HOME:-<not set>}"
    echo "  ANDROID_SDK_ROOT: ${ANDROID_SDK_ROOT:-<not set>}"
    if [[ -f "$LOCAL_PROPERTIES" ]]; then
        echo "  local.properties sdk.dir: $(grep '^sdk\.dir' "$LOCAL_PROPERTIES" 2>/dev/null || echo '<not set>')"
    fi

    echo -e "\n${BOLD}Gradle Wrapper:${RESET}"
    "$GRADLEW" --version | sed 's/^/  /'
}

# ------------------------------------------------------------------------------
# Artifact Collection and Summary
# ------------------------------------------------------------------------------
print_summary() {
    local end_time
    end_time=$(date +%s)
    local total_duration=$((end_time - START_TIME))

    echo -e "\n${BOLD}${GREEN}================================================================================"
    echo "                              BUILD SUMMARY                                     "
    echo "================================================================================${RESET}"
    echo -e "${BOLD}Target Command:${RESET}     $COMMAND"
    echo -e "${BOLD}Variant Filter:${RESET}     $VARIANT"
    echo -e "${BOLD}Total Duration:${RESET}     $(format_time $total_duration)"

    # Check for produced APKs
    local apk_dir="${PROJECT_ROOT}/app/build/outputs/apk"
    if [[ -d "$apk_dir" ]]; then
        local apks
        apks=$(find "$apk_dir" -type f -name "*.apk" 2>/dev/null || true)
        if [[ -n "$apks" ]]; then
            echo -e "\n${BOLD}${CYAN}Generated APK Packages:${RESET}"
            while IFS= read -r apk; do
                if [[ -n "$apk" ]]; then
                    local size
                    size=$(human_readable_size "$apk")
                    echo -e "  - ${GREEN}${apk#$PROJECT_ROOT/}${RESET} ${DIM}(${size})${RESET}"
                fi
            done <<< "$apks"
        fi
    fi

    # Check for produced AABs
    local bundle_dir="${PROJECT_ROOT}/app/build/outputs/bundle"
    if [[ -d "$bundle_dir" ]]; then
        local aabs
        aabs=$(find "$bundle_dir" -type f -name "*.aab" 2>/dev/null || true)
        if [[ -n "$aabs" ]]; then
            echo -e "\n${BOLD}${CYAN}Generated App Bundles (AAB):${RESET}"
            while IFS= read -r aab; do
                if [[ -n "$aab" ]]; then
                    local size
                    size=$(human_readable_size "$aab")
                    echo -e "  - ${GREEN}${aab#$PROJECT_ROOT/}${RESET} ${DIM}(${size})${RESET}"
                fi
            done <<< "$aabs"
        fi
    fi

    # Check for test reports (every module)
    local reports
    reports=$(find "$PROJECT_ROOT" -maxdepth 6 -type f -path "*/build/reports/tests/*/index.html" -not -path "*/build-logic/*" 2>/dev/null | sort || true)
    if [[ -n "$reports" ]]; then
        echo -e "\n${BOLD}${CYAN}Test Reports:${RESET}"
        while IFS= read -r report; do
            if [[ -n "$report" ]]; then
                echo -e "  - ${WHITE}${report#$PROJECT_ROOT/}${RESET}"
            fi
        done <<< "$reports"
    fi

    # Check for lint reports
    local lint_reports_dir="${PROJECT_ROOT}/app/build/reports"
    if [[ -d "$lint_reports_dir" ]]; then
        local lint_reports
        lint_reports=$(find "$lint_reports_dir" -maxdepth 1 -type f -name "lint-results*.html" 2>/dev/null || true)
        if [[ -n "$lint_reports" ]]; then
            echo -e "\n${BOLD}${CYAN}Lint Reports:${RESET}"
            while IFS= read -r report; do
                if [[ -n "$report" ]]; then
                    echo -e "  - ${WHITE}${report#$PROJECT_ROOT/}${RESET}"
                fi
            done <<< "$lint_reports"
        fi
    fi

    echo -e "\n${BOLD}${GREEN}✔ All requested operations finished successfully!${RESET}\n"
}

# ------------------------------------------------------------------------------
# Build Orchestrator
# ------------------------------------------------------------------------------
build_pipeline() {
    check_prerequisites

    # 1. Clean if requested or if clean command
    if [[ $FLAG_CLEAN -eq 1 || "$COMMAND" == "clean" ]]; then
        run_gradle "Cleaning build cache and output directories" clean
        if [[ "$COMMAND" == "clean" ]]; then
            print_summary
            return 0
        fi
    fi

    # 2. Stop daemon command
    if [[ "$COMMAND" == "stop-daemon" ]]; then
        run_gradle "Stopping Gradle daemons" --stop
        return 0
    fi

    # 3. Diagnostics
    if [[ "$COMMAND" == "diagnostics" ]]; then
        run_diagnostics
        return 0
    fi

    # 4. Stability Dump
    if [[ "$COMMAND" == "stability-dump" ]]; then
        case "$VARIANT" in
            debug)
                run_gradle "Updating Compose stability dump (Debug)" debugStabilityDump
                ;;
            release)
                run_gradle "Updating Compose stability dump (Release)" releaseStabilityDump
                ;;
            *)
                run_gradle "Updating Compose stability dump (All variants)" stabilityDump
                ;;
        esac
        print_summary
        return 0
    fi

    # 5. Stability Check
    if [[ "$COMMAND" == "stability" || "$COMMAND" == "check" || "$COMMAND" == "all" || $FLAG_STABILITY -eq 1 ]]; then
        if [[ $SKIP_STABILITY -eq 0 ]]; then
            case "$VARIANT" in
                debug)
                    run_gradle "Running Compose stability check (Debug)" debugStabilityCheck
                    ;;
                release)
                    run_gradle "Running Compose stability check (Release)" releaseStabilityCheck
                    ;;
                *)
                    run_gradle "Running Compose stability checks" stabilityCheck
                    ;;
            esac
            if [[ "$COMMAND" == "stability" ]]; then
                print_summary
                return 0
            fi
        fi
    fi

    # 6. Lint Tasks
    if [[ "$COMMAND" == "lint-fix" ]]; then
        run_gradle "Running Android Lint with automatic fixes" :app:lintFix
        print_summary
        return 0
    fi

    if [[ "$COMMAND" == "lint" || "$COMMAND" == "check" || "$COMMAND" == "all" || $FLAG_LINT -eq 1 ]]; then
        if [[ $SKIP_LINT -eq 0 ]]; then
            case "$VARIANT" in
                debug)
                    run_gradle "Running Android Lint (Debug)" :app:lintDebug
                    ;;
                release)
                    run_gradle "Running Android Lint (Release)" :app:lintRelease
                    ;;
                *)
                    run_gradle "Running Android Lint (All variants)" :app:lint
                    ;;
            esac
            if [[ "$COMMAND" == "lint" ]]; then
                print_summary
                return 0
            fi
        fi
    fi

    # 7. Unit Tests
    if [[ "$COMMAND" == "test" || "$COMMAND" == "check" || "$COMMAND" == "all" || $FLAG_TEST -eq 1 ]]; then
        if [[ $SKIP_TESTS -eq 0 ]]; then
            case "$VARIANT" in
                debug)
                    run_gradle "Running Unit Tests (Debug)" testDebugUnitTest :common-core:test
                    ;;
                release)
                    run_gradle "Running Unit Tests (Release)" testReleaseUnitTest :common-core:test
                    ;;
                *)
                    run_gradle "Running Unit Tests (All variants)" test
                    ;;
            esac
            if [[ "$COMMAND" == "test" ]]; then
                print_summary
                return 0
            fi
        fi
    fi

    # Check command finished if 'check'
    if [[ "$COMMAND" == "check" ]]; then
        print_summary
        return 0
    fi

    # 8. Connected / Instrumented Tests
    if [[ "$COMMAND" == "connected-test" ]]; then
        case "$VARIANT" in
            release)
                run_gradle "Running Connected Instrumented Tests (Release)" :app:connectedReleaseAndroidTest
                ;;
            *)
                run_gradle "Running Connected Instrumented Tests (Debug)" :app:connectedDebugAndroidTest
                ;;
        esac
        print_summary
        return 0
    fi

    # 9. Install on connected device
    if [[ "$COMMAND" == "install-debug" ]]; then
        run_gradle "Installing Debug APK to connected device" :app:installDebug
        print_summary
        return 0
    fi

    # 10. Assemble / Packaging (APKs and/or AABs)
    local assemble_tasks=()

    if [[ "$COMMAND" == "bundle" ]]; then
        case "$VARIANT" in
            debug)
                assemble_tasks+=(":app:bundleDebug")
                ;;
            release)
                assemble_tasks+=(":app:bundleRelease")
                ;;
            *)
                assemble_tasks+=(":app:bundle")
                ;;
        esac
    elif [[ "$COMMAND" == "debug" ]]; then
        assemble_tasks+=(":app:assembleDebug")
    elif [[ "$COMMAND" == "release" ]]; then
        assemble_tasks+=(":app:assembleRelease")
        assemble_tasks+=(":app:bundleRelease")
    else
        # assemble or all
        if [[ $FLAG_BUILD_APK -eq 1 ]]; then
            case "$VARIANT" in
                debug)
                    assemble_tasks+=(":app:assembleDebug")
                    ;;
                release)
                    assemble_tasks+=(":app:assembleRelease")
                    ;;
                *)
                    assemble_tasks+=(":app:assemble")
                    ;;
            esac
        fi

        if [[ $FLAG_BUILD_AAB -eq 1 ]]; then
            case "$VARIANT" in
                debug)
                    assemble_tasks+=(":app:bundleDebug")
                    ;;
                release)
                    assemble_tasks+=(":app:bundleRelease")
                    ;;
                *)
                    assemble_tasks+=(":app:bundle")
                    ;;
            esac
        fi
    fi

    if [[ ${#assemble_tasks[@]} -gt 0 ]]; then
        run_gradle "Building and packaging application artifacts" "${assemble_tasks[@]}"
    fi

    print_summary
}

# ------------------------------------------------------------------------------
# Script Entry Point
# ------------------------------------------------------------------------------
main() {
    parse_arguments "$@"
    build_pipeline
}

main "$@"
