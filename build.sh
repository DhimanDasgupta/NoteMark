            all|full)
                COMMAND="all"
                shift
                ;;
            build|assemble)
                COMMAND="assemble"
                shift
                ;;
            debug)
                COMMAND="debug"
                VARIANT="debug"
                shift
                ;;
            release)
                COMMAND="release"
                VARIANT="release"
                shift
                ;;
            bundle)
                COMMAND="bundle"
                shift
                ;;
            test|unit-test)
                COMMAND="test"
                shift
                ;;
            lint)
                COMMAND="lint"
                shift
                ;;
            lint-fix)
                COMMAND="lint-fix"
                shift
                ;;
            stability|stability-check)
                COMMAND="stability"
