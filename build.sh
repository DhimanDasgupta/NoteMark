#!/usr/bin/env bash
# ==============================================================================
# NoteMark - Comprehensive Build & Automation Script
# ==============================================================================
# This script provides a unified, robust interface for building, testing,
# linting, analyzing, and packaging the NoteMark Android application.
# ==============================================================================

set -euo pipefail

# ------------------------------------------------------------------------------
# Script & Project Constants
# ------------------------------------------------------------------------------
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="${SCRIPT_DIR}"
GRADLEW="${PROJECT_ROOT}/gradlew"
LOCAL_PROPERTIES="${PROJECT_ROOT}/local.properties"
START_TIME=$(date +%s)

# ------------------------------------------------------------------------------
# Color / Text Formatting Support
# ------------------------------------------------------------------------------
if [[ -t 1 ]] && [[ "${NO_COLOR:-}" != "1" ]] && [[ "${TERM:-}" != "dumb" ]]; then
    BOLD="\033[1m"
    DIM="\033[2m"
    RED="\033[0;31m"
    GREEN="\033[0;32m"
    YELLOW="\033[0;33m"
    BLUE="\033[0;34m"
    MAGENTA="\033[0;35m"
    CYAN="\033[0;36m"
    WHITE="\033[1;37m"
    RESET="\033[0m"
else
    BOLD=""
    DIM=""
    RED=""
    GREEN=""
    YELLOW=""
    BLUE=""
    MAGENTA=""
    CYAN=""
    WHITE=""
    RESET=""
fi

# ------------------------------------------------------------------------------
# Logging & Helper Functions
# ------------------------------------------------------------------------------
log_info() {
    echo -e "${CYAN}[INFO]${RESET} $*"
}

log_step() {
    echo -e "\n${BOLD}${BLUE}==>${RESET} ${BOLD}${WHITE}$*${RESET}"
}

log_success() {
    echo -e "${GREEN}[SUCCESS]${RESET} $*"
}

log_warn() {
    echo -e "${YELLOW}[WARN]${RESET} $*"
}

log_error() {
    echo -e "${RED}[ERROR]${RESET} $*" >&2
}

format_time() {
    local seconds=$1
    local min=$((seconds / 60))
    local sec=$((seconds % 60))
    if ((min > 0)); then
        printf "%dm %ds" "$min" "$sec"
    else
        printf "%ds" "$sec"
    fi
}

human_readable_size() {
    local file="$1"
    if [[ -f "$file" ]]; then
        if [[ "$OSTYPE" == "darwin"* ]]; then
            stat -f%z "$file" | awk '{ split("B KB MB GB", v); s=1; while($1>1024 && s<4){$1/=1024; s++} printf "%.2f %s", $1, v[s] }'
        else
            stat -c%s "$file" | awk '{ split("B KB MB GB", v); s=1; while($1>1024 && s<4){$1/=1024; s++} printf "%.2f %s", $1, v[s] }'
        fi
    else
        echo "0 B"
    fi
}

print_banner() {
    echo -e "${BOLD}${CYAN}"
    echo "================================================================================"
    echo "                      NoteMark Project Build System                             "
    echo "================================================================================"
    echo -e "${RESET}"
}

# ------------------------------------------------------------------------------
# Pre-flight Checks
# ------------------------------------------------------------------------------
check_prerequisites() {
    log_info "Checking build environment and prerequisites..."

    # Ensure gradlew exists and is executable
    if [[ ! -f "$GRADLEW" ]]; then
        log_error "Gradle wrapper (gradlew) not found at: $GRADLEW"
        exit 1
    fi

    if [[ ! -x "$GRADLEW" ]]; then
        log_warn "Setting executable permissions on gradlew..."
        chmod +x "$GRADLEW"
    fi

    # Check Java
    if command -v java >/dev/null 2>&1; then
        local java_ver
        java_ver=$(java -version 2>&1 | head -n 1)
        log_info "Java runtime: ${DIM}${java_ver}${RESET}"
    else
        log_error "Java is not installed or not available in PATH."
        exit 1
    fi

    # Check local.properties and required configuration
    if [[ ! -f "$LOCAL_PROPERTIES" ]]; then
        log_warn "local.properties not found! Creating default template..."
        cat << 'EOF' > "$LOCAL_PROPERTIES"
## Autogenerated local.properties template
# Location of the SDK. This is only used by Gradle.
# sdk.dir=/path/to/android/sdk
HEADER_VALUE_FOR_NOTE_MARK_API=local_dev_key
EOF
        log_warn "Created local.properties with placeholder HEADER_VALUE_FOR_NOTE_MARK_API."
    else
        if ! grep -q "^HEADER_VALUE_FOR_NOTE_MARK_API" "$LOCAL_PROPERTIES"; then
            log_warn "HEADER_VALUE_FOR_NOTE_MARK_API missing in local.properties. Appending placeholder..."
            echo "HEADER_VALUE_FOR_NOTE_MARK_API=local_dev_key" >> "$LOCAL_PROPERTIES"
        fi
    fi

    # Git details if available
    if command -v git >/dev/null 2>&1 && git -C "$PROJECT_ROOT" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
        local branch commit_sha
        branch=$(git -C "$PROJECT_ROOT" rev-parse --abbrev-ref HEAD 2>/dev/null || echo "unknown")
        commit_sha=$(git -C "$PROJECT_ROOT" rev-parse --short HEAD 2>/dev/null || echo "unknown")
        log_info "Git: ${DIM}branch=${branch}, commit=${commit_sha}${RESET}"
    fi
}

